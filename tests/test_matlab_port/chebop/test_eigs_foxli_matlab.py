def _csort(a):
    # Sort complex values by (real, imag) so two convergent lists align.
    return np.array(sorted(a, key=lambda z: (z.real, z.imag)))


@pytest.mark.slow
@pytest.mark.matlab
class TestChebopEigsFoxli:
    def test_eigenvalues_match_reference(self):
        # Kernel K(x, s) = exp(-i F (x - s)^2), scale = sqrt(i F / pi).
        def K(x, s):
            return np.exp(-1j * F * (x - s) ** 2)

        scale = np.sqrt(1j * F / np.pi)
        lam = np.asarray(
            fred_eigs(K, (-1.0, 1.0), k=80, which="LM", scale=scale, n=800))
        err = np.max(np.abs(_csort(lam) - _csort(LAM_V4)))
        # MATLAB uses tol 1e-10; allow a small margin for the dense solve.
        assert err < 1e-9
