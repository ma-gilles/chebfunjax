# ---------------------------------------------------------------------------
# Quasimatrix qr / svd of A = [1, x, x^2, x^3] on [-1, 1]
# ---------------------------------------------------------------------------


def _quasimatrix_cols():
    return [cj.chebfun(lambda t, k=k: t**k) for k in range(4)]


@pytest.mark.matlab
class TestQuasimatrixLinalg:
    def test_svd_singular_values(self):
        _, S, _ = chebfun_svd(_quasimatrix_cols())
        npt.assert_allclose(np.asarray(S), _REF["svd_S"], rtol=RTOL, atol=1e-13)

    def test_qr_rdiag(self):
        _, R = chebfun_qr(_quasimatrix_cols())
        npt.assert_allclose(np.diag(np.asarray(R)), _REF["qr_Rdiag"],
                            rtol=RTOL, atol=1e-13)

    def test_qr_r_full(self):
        _, R = chebfun_qr(_quasimatrix_cols())
        npt.assert_allclose(np.asarray(R), _REF["qr_R"], rtol=RTOL, atol=1e-12)


# ---------------------------------------------------------------------------
# ode45 / ode113 — accuracy of an IVP solve (documented Gate-3 metric)
# ---------------------------------------------------------------------------

# scipy solve_ivp adaptive step control (rtol 1e-6) => NOT a 1e-12 pin; the
# reference is the analytic solution and we check solver accuracy only.
_ODE_RTOL = 1e-5
_ODE_ATOL = 1e-6


@pytest.mark.matlab
class TestODEAccuracy:
    def _eval(self, sol):
        tt = np.asarray(_REF["ode_t"], dtype=float)
        return np.array([float(sol(jnp.float64(t))) for t in tt])

    def test_ode45_decay(self):
        sol = ode45(lambda t, y: -y, (0.0, 2.0), jnp.array([1.0]))
        npt.assert_allclose(self._eval(sol), _REF["ode_exact"],
                            rtol=_ODE_RTOL, atol=_ODE_ATOL)

    def test_ode113_decay(self):
        sol = ode113(lambda t, y: -y, (0.0, 2.0), jnp.array([1.0]))
        npt.assert_allclose(self._eval(sol), _REF["ode_exact"],
                            rtol=_ODE_RTOL, atol=_ODE_ATOL)
