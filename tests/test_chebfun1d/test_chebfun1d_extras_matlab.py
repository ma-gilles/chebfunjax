# ---------------------------------------------------------------------------
# conv — convolution of two chebfuns
# ---------------------------------------------------------------------------


@pytest.mark.matlab
class TestConv:
    def _h(self):
        f = cj.chebfun(lambda t: jnp.sin(t))
        g = cj.chebfun(lambda t: jnp.exp(t))
        return f.conv(g)

    def test_domain(self):
        h = self._h()
        got = np.array([float(h.domain.a), float(h.domain.b)])
        npt.assert_allclose(got, np.asarray(_REF["conv_dom"], dtype=float),
                            rtol=RTOL, atol=1e-13)

    def test_eval(self):
        h = self._h()
        cpts = jnp.asarray(_REF["conv_pts"], dtype=jnp.float64)
        npt.assert_allclose(np.asarray(h(cpts)), _REF["conv_eval"],
                            rtol=RTOL, atol=1e-11)


